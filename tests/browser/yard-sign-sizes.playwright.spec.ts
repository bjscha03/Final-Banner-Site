import { expect, test } from '@playwright/test';
import sharp from 'sharp';
import { readFileSync } from 'node:fs';
const catalog = JSON.parse(readFileSync(new URL('../../shared/yard-sign-sizes.json', import.meta.url), 'utf8'));
test.beforeEach(async({page},info)=>{
 await page.context().addCookies([{name:'compact_browser_scenario',value:`selector-yard-sizes-${info.project.name}-${info.testId}`,url:'http://127.0.0.1:4175'}]);
});
for(const route of ['/design?product=yard-signs','/google-ads-banner?product=yard-signs'])test(`all sizes, rules and prices on ${route}`,async({page})=>{
 await page.goto(route);
 const select=page.locator('#yard-sign-size');
 await expect(select).toHaveValue('24x18');
 await expect(select.locator('option')).toHaveCount(5);
 const quantity=page.locator('#yard-quantity-section');
 const input=quantity.getByRole('spinbutton',{name:'Quantity'});
 for(const size of catalog.sizes){
   await select.selectOption(size.id);
   await input.fill(String(size.minQuantity));await input.blur();
   await expect(input).toHaveValue(String(size.minQuantity));
   await expect(quantity).toContainText(`increments of ${size.increment}`);
   await expect(quantity.getByRole('button',{name:'Decrease quantity'})).toBeDisabled();
   await page.locator('#yard-print-side-section').getByRole('button',{name:/Single-Sided/}).click();
   await expect(page.locator('#yard-print-side-section')).toContainText(`$${(size.singleCents/100).toFixed(2)}/sign`);
   const total=quantity.locator('[data-yard-order-total]');
   const amount=size.minQuantity*size.singleCents/100;
   await expect(total).toHaveText(new RegExp(`^\\$(${amount.toFixed(2)}|${(amount*.8).toFixed(2)})$`));
   await quantity.getByRole('button',{name:'Increase quantity'}).click();
   await expect(input).toHaveValue(String(size.minQuantity+size.increment));
   await input.fill(String(size.maxQuantity));await input.blur();
   await expect(quantity.getByRole('button',{name:'Increase quantity'})).toBeDisabled();
   await input.fill(String(size.minQuantity+1));await input.blur();
   await expect(input).toHaveValue(String(size.maxQuantity));
   await page.locator('#yard-print-side-section').getByRole('button',{name:/Double-Sided/}).click();
   await expect(page.locator('#yard-print-side-section')).toContainText('same artwork prints on both sides');
   expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
 }
});
test('portrait upload, landscape switch, AI fit, checkout and cart edit preserve size',async({page},info)=>{
 await page.goto('/design?product=yard-signs');
 await page.locator('#yard-sign-size').selectOption('18x24');
 const quantity=page.locator('#yard-quantity-section').getByRole('spinbutton',{name:'Quantity'});
 await quantity.fill('8');await quantity.blur();
 const artwork=await sharp({create:{width:900,height:1200,channels:3,background:'#18448d'}}).png().toBuffer();
 const chooser=page.waitForEvent('filechooser');
 await page.locator('#yard-upload-section').getByRole('button',{name:/Upload your artwork/}).click();
 await(await chooser).setFiles({name:'portrait-yard.png',mimeType:'image/png',buffer:artwork});
 const heading=page.getByRole('heading',{name:'Yard Sign Preview',exact:true});
 await expect(heading).toBeVisible();
 const canvas=page.getByTestId('artwork-canvas');
 await expect.poll(async()=>{const b=await canvas.boundingBox();return b?Math.abs(b.width/b.height-.75):10}).toBeLessThan(.02);
 await page.getByRole('button',{name:'Done',exact:true}).click();await expect(heading).toHaveCount(0);
 await page.locator('#yard-sign-size').selectOption('24x36');
 await expect(quantity).toHaveValue('8');
 await page.locator('#yard-upload-section').getByRole('button',{name:/Preview/}).first().click();
 await expect(heading).toBeVisible();
 await expect.poll(async()=>{const b=await canvas.boundingBox();return b?Math.abs(b.width/b.height-1.5):10}).toBeLessThan(.02);
 const fitRequest=page.waitForRequest(r=>r.url().includes('/ai-designer-fit')&&r.method()==='POST');
 await page.getByRole('button',{name:'Fit my design with AI',exact:true}).filter({visible:true}).first().click();
 const req=await fitRequest;
 expect(req.postDataJSON()).toMatchObject({widthIn:36,heightIn:24,productType:'yard_sign'});
 const dialog=page.getByRole('dialog').filter({has:page.getByRole('button',{name:'Approve design'})});
 await expect(dialog.getByRole('img',{name:'Your fitted design'})).toBeVisible({timeout:60000});
 await dialog.getByRole('button',{name:'Approve design'}).click();
 await page.getByRole('button',{name:'Done',exact:true}).click();await expect(heading).toHaveCount(0);
 await page.locator('#yard-finishing-section').getByText('With stakes',{exact:true}).click();
 await page.locator('#yard-print-side-section').getByRole('button',{name:/Double-Sided/}).click();
 await page.getByRole('button',{name:'Checkout',exact:true}).filter({visible:true}).first().click();
 await expect(page).toHaveURL(/\/checkout/,{timeout:60000});
 const items=await page.evaluate(()=>JSON.parse(localStorage.getItem('cart-storage')||'{}').state.items);
 expect(items).toHaveLength(1);
 expect(items[0]).toMatchObject({product_type:'yard_sign',width_in:36,height_in:24,quantity:8,yard_sign_sidedness:'double',yard_sign_step_stakes_qty:8,unit_price_cents:2400,line_total_cents:20400});
 expect(items[0].yard_sign_designs[0].placementPreview).toMatchObject({widthIn:36,heightIn:24});
 await expect(page.getByText(/24.*36/).first()).toBeVisible();
 await page.goto(`/design?product=yard-signs&editItem=${encodeURIComponent(items[0].id)}`);
 await expect(page.locator('#yard-sign-size')).toHaveValue('24x36');
 await expect(quantity).toHaveValue('8');
 await page.screenshot({path:info.outputPath('yard-size-edit.png')});
});
