// Keep legacy CommonJS email workers on the same scheduling source as the UI.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import ts from 'typescript';

const dir = new URL('../netlify/functions/_shared/delivery/', import.meta.url);
await mkdir(dir, { recursive: true });
for (const name of ['timezone', 'cutoffs', 'engine', 'orderEstimate']) {
  const source = await readFile(new URL(`../src/lib/delivery/${name}.ts`, import.meta.url), 'utf8');
  const output = '// Generated by scripts/generate-order-delivery.mjs. Edit src/lib/delivery instead.\n'
    + ts.transpileModule(source, { compilerOptions: {
      target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS, removeComments: true,
    } }).outputText.replace(/require\("\.\/(timezone|cutoffs|engine)"\)/g, 'require("./$1.cjs")');
  const target = new URL(`${name}.cjs`, dir);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw new Error('Run node scripts/generate-order-delivery.mjs before building.');
  } else await writeFile(target, output);
}
