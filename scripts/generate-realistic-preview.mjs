// Share the customer preview's geometry/mask with the email PNG renderer.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import ts from 'typescript';

const files = {
  cartGrommet: 'src/lib/cartGrommet.ts',
  grommetPositions: 'src/lib/preview/grommetPositions.ts',
  grommets: 'src/lib/preview/grommets.ts',
  realisticBanner: 'src/lib/preview/realisticBanner.ts',
};
const dir = new URL('../netlify/functions/_shared/realistic-preview/', import.meta.url);
await mkdir(dir, { recursive: true });
for (const [name, path] of Object.entries(files)) {
  const source = await readFile(new URL(`../${path}`, import.meta.url), 'utf8');
  const output = '// Generated by scripts/generate-realistic-preview.mjs. Edit src/lib instead.\n'
    + ts.transpileModule(source, { compilerOptions: {
      target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS, removeComments: true,
    } }).outputText.replace(/require\("(?:@\/lib\/|\.\/)(cartGrommet|grommetPositions|grommets)"\)/g, 'require("./$1.cjs")');
  const target = new URL(`${name}.cjs`, dir);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw new Error('Run node scripts/generate-realistic-preview.mjs before building.');
  } else await writeFile(target, output);
}
