import {readFile,writeFile} from 'node:fs/promises';
const source=new URL('../shared/specialty-options.cjs',import.meta.url);
const target=new URL('../shared/specialty-options.mjs',import.meta.url);
const content='// Generated by scripts/generate-specialty-options.mjs. Edit specialty-options.cjs.\n'+(await readFile(source,'utf8'))
  .replace("'use strict';\n",'')
  .replace("const profiles = require('./specialty-configuration.json');","import profiles from './specialty-configuration.json';")
  .replace("const release = require('./specialty-release.json');","import release from './specialty-release.json';")
  .replace('module.exports=','export default ');
if(process.argv.includes('--check')) {
  if(await readFile(target,'utf8')!==content)throw new Error('Run node scripts/generate-specialty-options.mjs before building.');
} else await writeFile(target,content);
const discountSource=new URL('../shared/specialty-discount-policy.cjs',import.meta.url);
const discountTarget=new URL('../shared/specialty-discount-policy.mjs',import.meta.url);
const discountContent='// Generated by scripts/generate-specialty-options.mjs.\n'+(await readFile(discountSource,'utf8'))
  .replace("'use strict';\n",'')
  .replace("const policy = require('./specialty-pricing-policy.json');","import policy from './specialty-pricing-policy.json';")
  .replace('module.exports =','export default');
if(process.argv.includes('--check')) {
  if(await readFile(discountTarget,'utf8')!==discountContent)throw new Error('Regenerate specialty discount policy.');
} else await writeFile(discountTarget,discountContent);
